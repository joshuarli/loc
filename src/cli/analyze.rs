/// Arguments for `loc` itself: the paths to analyze and the analysis settings.
#[expect(clippy::struct_excessive_bools, reason = "CLI flags are inherently boolean")]
pub struct AnalyzeArgs {
	pub source: SourceArgs,
	pub format: FormatArgs,
	pub quiet: bool,
	pub verbose: bool,
	pub no_gitignore: bool,
	pub no_gitattributes: bool,
	pub git: bool,
	pub symlinks: bool,
	pub percent_precision: u8,
	pub language_sort: LanguageSortKey,
	pub sort_direction: SortDirection,
	pub min_lines: Option<u64>,
	pub by_dir: bool,
}

/// Which files are counted: shared by the main command and `loc diff`.
#[derive(Default)]
#[expect(clippy::struct_excessive_bools, reason = "CLI flags are inherently boolean")]
pub struct SourceArgs {
	pub config: Option<PathBuf>,
	pub no_config: bool,
	pub paths: Vec<PathBuf>,
	pub include_generated: bool,
	pub max_depth: Option<usize>,
	pub hidden: bool,
	pub exclude: Vec<String>,
	pub include_lang: Vec<String>,
	pub exclude_lang: Vec<String>,
	pub ext: Vec<String>,
	pub fail_on_error: bool,
}

/// How results are shown: shared by the main command and `loc diff`.
pub struct FormatArgs {
	pub number_style: NumberStyle,
	pub size_style: SizeStyle,
	pub indent: IndentStyle,
	pub output: OutputFormat,
	pub top_languages: Option<usize>,
}

impl Default for AnalyzeArgs {
	fn default() -> Self {
		Self {
			source: SourceArgs::default(),
			format: FormatArgs::default(),
			quiet: false,
			verbose: false,
			no_gitignore: false,
			no_gitattributes: false,
			git: false,
			symlinks: false,
			percent_precision: 1,
			language_sort: LanguageSortKey::Lines,
			sort_direction: SortDirection::Desc,
			min_lines: None,
			by_dir: false,
		}
	}
}

impl Default for FormatArgs {
	fn default() -> Self {
		Self {
			number_style: NumberStyle::Plain,
			size_style: SizeStyle::Binary,
			indent: IndentStyle::Tab,
			output: OutputFormat::Human,
			top_languages: None,
		}
	}
}

fn take_value(option: &OptionSpec, raw: Option<OsString>) -> Result<OsString, CliError> {
	raw.ok_or_else(|| CliError::new(format!("internal error: option '{}' is not a flag", option.long)))
}

fn parse_number<T>(option: &OptionSpec, raw: &std::ffi::OsStr) -> Result<T, CliError>
where
	T: FromStr,
	T::Err: fmt::Display,
{
	let value = command::utf8_value(option, raw)?;
	value.parse().map_err(|error| CliError::new(format!("invalid value '{value}' for '{}': {error}", option.spelling())))
}

pub fn parse_top_languages(value: &str) -> Result<usize, String> {
	match value.parse() {
		Ok(0) => Err("must be at least 1 (use --quiet for totals only)".into()),
		Ok(n) => Ok(n),
		Err(error) => Err(error.to_string()),
	}
}

pub fn split_comma(list: &mut Vec<String>, value: &str) {
	list.extend(value.split(',').map(str::to_owned));
}

fn enum_value<T>(option: &OptionSpec, raw: &std::ffi::OsStr, from_cli: fn(&str) -> Option<T>) -> Result<T, CliError> {
	let value = command::utf8_value(option, raw)?;
	from_cli(value.as_str())
		.ok_or_else(|| CliError::new(format!("internal error: '{value}' is not a known value for '{}'", option.spelling())))
}

fn extend_comma(option: &OptionSpec, raw: Option<OsString>, list: &mut Vec<String>) -> Result<(), CliError> {
	let value = command::utf8_value(option, take_value(option, raw)?.as_os_str())?;
	split_comma(list, &value);
	Ok(())
}

pub fn apply_source(option: &'static OptionSpec, args: &mut SourceArgs, raw: Option<OsString>) -> Result<(), CliError> {
	match option.id {
		ids::CONFIG => args.config = Some(PathBuf::from(take_value(option, raw)?)),
		ids::NO_CONFIG => args.no_config = true,
		ids::INCLUDE_GENERATED => args.include_generated = true,
		ids::MAX_DEPTH => args.max_depth = Some(parse_number(option, take_value(option, raw)?.as_os_str())?),
		ids::HIDDEN => args.hidden = true,
		ids::EXCLUDE => {
			let value = command::utf8_value(option, take_value(option, raw)?.as_os_str())?;
			args.exclude.push(value);
		}
		ids::INCLUDE_LANG => extend_comma(option, raw, &mut args.include_lang)?,
		ids::EXCLUDE_LANG => extend_comma(option, raw, &mut args.exclude_lang)?,
		ids::EXT => extend_comma(option, raw, &mut args.ext)?,
		ids::FAIL_ON_ERROR => args.fail_on_error = true,
		_ => return Err(CliError::new(format!("internal error: option --{} is not a source option", option.long))),
	}
	Ok(())
}

pub fn apply_format(option: &'static OptionSpec, args: &mut FormatArgs, raw: Option<OsString>) -> Result<(), CliError> {
	match option.id {
		ids::NUMBER_STYLE => args.number_style = enum_value(option, take_value(option, raw)?.as_os_str(), NumberStyle::from_cli)?,
		ids::SIZE_STYLE => args.size_style = enum_value(option, take_value(option, raw)?.as_os_str(), SizeStyle::from_cli)?,
		ids::INDENT => {
			let value = command::utf8_value(option, take_value(option, raw)?.as_os_str())?;
			args.indent = IndentStyle::from_str(&value)
				.map_err(|error| CliError::new(format!("invalid value '{value}' for '{}': {error}", option.spelling())))?;
		}
		ids::OUTPUT => args.output = enum_value(option, take_value(option, raw)?.as_os_str(), OutputFormat::from_cli)?,
		ids::TOP_LANGUAGES => {
			let value = command::utf8_value(option, take_value(option, raw)?.as_os_str())?;
			args.top_languages = Some(
				parse_top_languages(&value).map_err(|error| CliError::new(format!("invalid value '{value}' for '{}': {error}", option.spelling())))?,
			);
		}
		_ => return Err(CliError::new(format!("internal error: option --{} is not a format option", option.long))),
	}
	Ok(())
}

pub fn apply_shared(
	option: &'static OptionSpec,
	source: &mut SourceArgs,
	format: &mut FormatArgs,
	raw: Option<OsString>,
) -> Result<(), CliError> {
	if SOURCE_OPTIONS.iter().any(|o| o.id == option.id) {
		apply_source(option, source, raw)
	} else if FORMAT_OPTIONS.iter().any(|o| o.id == option.id) {
		apply_format(option, format, raw)
	} else {
		Err(CliError::new(format!("internal error: unexpected option --{}", option.long)))
	}
}

fn apply_option(option: &'static OptionSpec, args: &mut AnalyzeArgs, raw: Option<OsString>) -> Result<(), CliError> {
	match option.id {
		ids::QUIET => args.quiet = true,
		ids::VERBOSE => args.verbose = true,
		ids::NO_GITIGNORE => args.no_gitignore = true,
		ids::NO_GITATTRIBUTES => args.no_gitattributes = true,
		ids::GIT => args.git = true,
		ids::SYMLINKS => args.symlinks = true,
		ids::BY_DIR => args.by_dir = true,
		ids::PERCENT_PRECISION => {
			let raw = take_value(option, raw)?;
			let value = parse_number::<u8>(option, raw.as_os_str())?;
			if value > 6 {
				let value = command::utf8_value(option, raw.as_os_str())?;
				return Err(CliError::new(format!("invalid value '{value}' for '{}': must be at most 6", option.spelling())));
			}
			args.percent_precision = value;
		}
		ids::LANGUAGE_SORT => args.language_sort = enum_value(option, take_value(option, raw)?.as_os_str(), LanguageSortKey::from_cli)?,
		ids::SORT_DIRECTION => args.sort_direction = enum_value(option, take_value(option, raw)?.as_os_str(), SortDirection::from_cli)?,
		ids::MIN_LINES => args.min_lines = Some(parse_number(option, take_value(option, raw)?.as_os_str())?),
		_ => apply_shared(option, &mut args.source, &mut args.format, raw)?,
	}
	Ok(())
}

#[expect(clippy::unnecessary_wraps, reason = "positional callbacks share a fallible signature across commands")]
fn apply_positional(args: &mut AnalyzeArgs, value: OsString) -> Result<(), CliError> {
	args.source.paths.push(PathBuf::from(value));
	Ok(())
}

pub fn parse_root(full_name: &str, version_allowed: bool, argv: Vec<OsString>) -> Result<Flow<AnalyzeArgs>, CliError> {
	command::parse_command(&super::ROOT_SPEC, full_name, AnalyzeArgs::default(), Parser::from_iter(argv), version_allowed, apply_option, apply_positional)
}

pub fn parse_prefix(prefix: &[OsString]) -> Result<Flow<AnalyzeArgs>, CliError> {
	let argv = std::iter::once(OsString::from("loc")).chain(prefix.iter().cloned());
	parse_root("loc", true, argv.collect())
}

pub fn execute(args: &AnalyzeArgs, seen: &HashSet<&'static str>) -> Result<()> {
	let config = super::merge::merge_config(super::merge::base_config(&args.source)?, args, seen)?;
	let reads_list = config.paths.iter().any(|path| path.as_os_str() == "-");
	let (roots, results) = if reads_list {
		ensure!(
			config.paths.len() == 1,
			"`-` reads the paths to count from standard input, so it can't be given with other paths"
		);
		let mut list = Vec::new();
		io::stdin().lock().read_to_end(&mut list).context("couldn't read the paths from standard input")?;
		(config.paths.clone(), crate::analysis::count_listed(&crate::analysis::parse_list(&list), &(&config).into())?)
	} else {
		super::merge::ensure_path(&config)?;
		let roots = roots(&config);
		let mut results = AnalysisResults::default();
		for root in &roots {
			let analyzer = CodeAnalyzer::new(root, (&config).into());
			let analyzer = if roots.len() > 1 { analyzer.showing_root() } else { analyzer };
			results.merge(analyzer.analyze()?);
		}
		(roots, results)
	};
	let view_options: crate::display::ViewOptions = (&config).into();
	let mut stdout = io::BufWriter::new(io::stdout().lock());
	crate::display::write_output(config.display.output, &results, &roots, view_options, &mut stdout)?;
	stdout.flush()?;
	if config.analysis.fail_on_error && results.skipped_entries() > 0 {
		let skipped = results.skipped_entries();
		return Err(anyhow!("Skipped {skipped} {} due to errors", crate::display::formatting::pluralize(skipped, "entry", "entries")));
	}
	Ok(())
}

fn roots(config: &Config) -> Vec<PathBuf> {
	let given = &config.paths;
	let resolved: Vec<PathBuf> =
		given.iter().map(|path| path.canonicalize().unwrap_or_else(|_| path.clone())).collect();
	given
		.iter()
		.enumerate()
		.filter(|&(i, _)| {
			!resolved
				.iter()
				.enumerate()
				.any(|(j, other)| j != i && resolved[i].starts_with(other) && (resolved[i] != *other || j < i))
		})
		.map(|(_, path)| path.clone())
		.collect()
}
